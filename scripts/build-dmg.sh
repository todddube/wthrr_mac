#!/usr/bin/env bash
# build-dmg.sh — build wthrr (Release), sign it, and package it as a styled DMG
#
# Usage:
#   ./scripts/build-dmg.sh            # build + sign + DMG
#   ./scripts/build-dmg.sh --bg-only  # regenerate background image only
#   ./scripts/build-dmg.sh --dmg-only # skip Xcode build, re-sign + re-package
#
# Requirements (install via Homebrew):
#   brew install create-dmg
#
# Signing strategy (auto-detected):
#   Developer ID Application cert present → signs with Developer ID + hardened runtime
#     • Unlocks right-click → Open without any further bypass
#     • Run notarytool + stapler after this script to remove all Gatekeeper prompts
#   No Developer ID cert → ad-hoc signing ("-")
#     • Binary is signed; users bypass via System Settings → Privacy & Security → "Open Anyway"
#     • Or: right-click the app in Finder → Open → Open in the dialog
#
# DMG background (scripts/dmg-background.png) is generated by
# scripts/create_dmg_bg.py — a stdlib-only Python 3 script that draws:
#   • Aurora gradient wash across the top
#   • Snowflakes on the left, rain streaks on the right
#   • Lightning bolt and fog wisps
#   • Soft glows beneath the app icon + Applications drop zones

set -euo pipefail

# ── Config ────────────────────────────────────────────────────────────────────
PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCHEME="wthrr"
BUILD_DIR="$PROJECT_ROOT/build"
APP_NAME="wthrr"
BG_SCRIPT="$PROJECT_ROOT/scripts/create_dmg_bg.py"
BG_IMAGE="$PROJECT_ROOT/scripts/dmg-background.png"

# Parse flags
BG_ONLY=false
DMG_ONLY=false
for arg in "$@"; do
    case "$arg" in
        --bg-only)  BG_ONLY=true  ;;
        --dmg-only) DMG_ONLY=true ;;
        *) echo "Unknown flag: $arg"; exit 1 ;;
    esac
done

# Read version from Xcode build settings
VERSION=$(xcodebuild -project "$PROJECT_ROOT/wthrr.xcodeproj" \
    -scheme "$SCHEME" -showBuildSettings 2>/dev/null \
    | awk '/MARKETING_VERSION/{print $3; exit}')
VERSION="${VERSION:-1.0}"
BUILD_NUM=$(xcodebuild -project "$PROJECT_ROOT/wthrr.xcodeproj" \
    -scheme "$SCHEME" -showBuildSettings 2>/dev/null \
    | awk '/CURRENT_PROJECT_VERSION/{print $3; exit}')
BUILD_NUM="${BUILD_NUM:-1}"

DMG_OUT="$BUILD_DIR/${APP_NAME}-${VERSION}.dmg"

# ── Helpers ───────────────────────────────────────────────────────────────────
header()  { echo; echo "▸ $*"; }
success() { echo "  ✓ $*"; }
info()    { echo "  · $*"; }

# ── Background-only mode ──────────────────────────────────────────────────────
if $BG_ONLY; then
    header "Regenerating DMG background only"
    python3 "$BG_SCRIPT"
    success "dmg-background.png ready at $BG_IMAGE"
    exit 0
fi

# ── Preflight ─────────────────────────────────────────────────────────────────
header "Preflight  (wthrr $VERSION, build $BUILD_NUM)"
if ! command -v create-dmg &>/dev/null; then
    echo
    echo "  create-dmg not found. Install it:"
    echo "    brew install create-dmg"
    echo
    exit 1
fi
success "create-dmg found"
success "Version $VERSION  ·  Build $BUILD_NUM"

# ── Step 1 — DMG background ───────────────────────────────────────────────────
header "Generating DMG background (aurora + weather showcase)"
python3 "$BG_SCRIPT"
success "dmg-background.png ready"

if ! $DMG_ONLY; then
    # ── Step 2 — Clean ────────────────────────────────────────────────────────
    header "Cleaning build/"
    rm -rf "$BUILD_DIR"
    mkdir -p "$BUILD_DIR"
    success "Clean"

    # ── Step 3 — Build ────────────────────────────────────────────────────────
    header "Building $SCHEME (Release)…"
    xcodebuild build \
        -project         "$PROJECT_ROOT/wthrr.xcodeproj" \
        -scheme          "$SCHEME" \
        -configuration   Release \
        -derivedDataPath "$BUILD_DIR/DerivedData" \
        CODE_SIGN_IDENTITY="" \
        CODE_SIGNING_REQUIRED=NO \
        CODE_SIGNING_ALLOWED=NO \
        2>&1 | grep -E "^(Build|error:|warning:|CompileSwift|Ld )" || true
    echo
    success "Build complete"
fi

# ── Step 4 — Locate .app ──────────────────────────────────────────────────────
APP_PATH=$(find "$BUILD_DIR/DerivedData" -name "$APP_NAME.app" -maxdepth 6 | head -1)
if [[ -z "$APP_PATH" ]]; then
    echo "ERROR: Could not find $APP_NAME.app in $BUILD_DIR/DerivedData"
    echo "       Run without --dmg-only first to build the app."
    exit 1
fi
success "App → $APP_PATH"

# Stage the .app in /tmp — outside iCloud Drive so the file provider daemon
# can't re-add com.apple.fileprovider.fpfs#P between our xattr strip and signing.
STAGE_DIR=$(mktemp -d -t wthrr-sign)
trap 'rm -rf "$STAGE_DIR"' EXIT
cp -R "$APP_PATH" "$STAGE_DIR/"

# ── Step 4.5 — Sign the .app ─────────────────────────────────────────────────
header "Code-signing ${APP_NAME}.app"
STAGED_APP="$STAGE_DIR/$APP_NAME.app"
ENTITLEMENTS="$PROJECT_ROOT/wthrr/wthrr.entitlements"

# Strip all Finder/iCloud metadata from the bundle root and its contents.
# Both com.apple.FinderInfo and com.apple.fileprovider.fpfs#P must be cleared
# before codesign runs; the file provider re-adds them if the path is in iCloud.
xattr -c  "$STAGED_APP"    # clear root directory itself
xattr -rc "$STAGED_APP"    # clear everything inside recursively

# Detect Developer ID Application certificate (requires paid Apple Developer Program).
# Falls back to ad-hoc ("-") which is free and still enables the Gatekeeper bypass
# via right-click → Open or System Settings → Privacy & Security → "Open Anyway".
DEV_ID_LINE=$(security find-identity -v -p codesigning 2>/dev/null \
    | grep "Developer ID Application" | head -1 || true)

if [[ -n "$DEV_ID_LINE" ]]; then
    DEV_ID=$(echo "$DEV_ID_LINE" | sed 's/.*"\(.*\)".*/\1/')
    info "Developer ID found: $DEV_ID"
    # --options runtime: hardens the binary (required for notarization)
    # --timestamp:       embeds a secure timestamp (required for notarization)
    codesign --force --deep \
        --sign         "$DEV_ID" \
        --options      runtime \
        --entitlements "$ENTITLEMENTS" \
        --timestamp \
        "$STAGED_APP"
    success "Signed with Developer ID (notarization-ready)"
    info "Optional next step: xcrun notarytool submit + xcrun stapler staple"
else
    info "No Developer ID Application cert — using ad-hoc signing."
    info "Users bypass via: right-click → Open  OR  System Settings → Privacy & Security → 'Open Anyway'"
    # Ad-hoc sign the entire bundle including all nested binaries/frameworks.
    # The sandbox entitlement is omitted for ad-hoc builds — it requires a real
    # Developer ID cert to be valid. The app runs unsandboxed, which is normal
    # for direct-distribution macOS apps outside the App Store.
    codesign --force --deep \
        --sign "-" \
        "$STAGED_APP"
    success "Ad-hoc signed"
fi

# Quick sanity check — print signature info
codesign --display --verbose=1 "$STAGED_APP" 2>&1 | grep -E "(Authority|Identifier|TeamIdentifier)" || true

# ── Step 5 — Build DMG ────────────────────────────────────────────────────────
header "Packaging DMG: ${APP_NAME}-${VERSION}.dmg"
rm -f "$DMG_OUT"
mkdir -p "$BUILD_DIR"

# DMG layout (860×520 window, 2× background 1720×1040):
#   App icon        x=215  y=260  (left zone, vertically centered)
#   Applications    x=645  y=260  (right zone, vertically centered)
#   Icon size 128 px (create-dmg maximum)

create-dmg \
    --volname           "$APP_NAME" \
    --volicon           "$APP_PATH/Contents/Resources/AppIcon.icns" \
    --background        "$BG_IMAGE" \
    --window-pos        200 120 \
    --window-size       860 520 \
    --text-size         14 \
    --icon-size         128 \
    --icon              "$APP_NAME.app" 215 260 \
    --hide-extension    "$APP_NAME.app" \
    --app-drop-link     645 260 \
    --no-internet-enable \
    "$DMG_OUT" \
    "$STAGE_DIR/"

success "DMG → $DMG_OUT"

# ── Done ──────────────────────────────────────────────────────────────────────
DMG_SIZE=$(du -sh "$DMG_OUT" | cut -f1)
echo
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  wthrr $VERSION (build $BUILD_NUM)  •  $DMG_SIZE"
echo "  $DMG_OUT"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Next: ./scripts/release.sh $VERSION"
echo ""
echo "  Gatekeeper bypass for users (ad-hoc build):"
echo "    • Right-click wthrr.app → Open → Open"
echo "    • OR: System Settings → Privacy & Security → 'Open Anyway'"
echo ""
echo "  For zero-prompt installs: get a Developer ID Application"
echo "  cert (\$99/yr Apple Developer Program) then re-run this"
echo "  script + notarize: xcrun notarytool submit / xcrun stapler staple"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
